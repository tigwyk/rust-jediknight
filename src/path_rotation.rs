/// State for the non-pivot path orientation branch. Angles are pitch, yaw, roll in degrees.
#[derive(Clone, Debug, Default, PartialEq)]
pub(crate) struct PathRotation {
    /// Engine row-vector orientation at the start of the segment.
    pub(crate) start_matrix: [[f32; 3]; 3],
    /// Current engine row-vector orientation.
    pub(crate) matrix: [[f32; 3]; 3],
    pub(crate) delta: [f32; 3],
    pub(crate) target: [f32; 3],
    pub(crate) rate: f32,
    pub(crate) progress: f32,
    pub(crate) active: bool,
}

impl PathRotation {
    /// Prepare a segment from the current and target Euler angles and duration in seconds.
    pub(crate) fn prepare(current: [f32; 3], target: [f32; 3], duration: f32) -> Self {
        let matrix = build_rotation(current);
        let extracted = extract_angles(matrix);
        let mut delta = [0.0; 3];
        for i in 0..3 {
            let angle = (target[i] - extracted[i]).rem_euclid(360.0);
            delta[i] = if angle > 180.0 { angle - 360.0 } else { angle };
            if delta[i].abs() < 2.5 {
                delta[i] = 0.0;
            }
        }
        let active = delta != [0.0; 3];
        Self { start_matrix: matrix, matrix, delta, target, rate: if active { 1.0 / duration } else { 0.0 }, progress: 0.0, active }
    }

    /// Advance by seconds. Completion snaps to the target matrix, as the engine does.
    pub(crate) fn advance(&mut self, dt: f32) {
        if !self.active || dt == 0.0 {
            return;
        }
        self.progress += self.rate * dt;
        if self.progress > 1.0 {
            self.progress = 1.0;
        }
        let rotation = build_rotation(self.delta.map(|angle| angle * self.progress));
        self.matrix = multiply(self.start_matrix, rotation);
        if self.progress >= 1.0 {
            self.matrix = build_rotation(self.target);
            self.active = false;
        }
    }

    pub(crate) fn current_euler(&self) -> [f32; 3] {
        extract_angles(self.matrix)
    }
}

/// `rdMatrix_PostRotate34` (`0x441a30`) on the pivot's orientation and offset.
pub(crate) fn pivot_pose(start: [f32; 3], offset: [f32; 3], angles: [f32; 3], pre: bool) -> ([f32; 3], [f32; 3]) {
    let rotation = build_rotation(angles);
    let start = build_rotation(start);
    let matrix = if pre { multiply(rotation, start) } else { multiply(start, rotation) };
    let offset = [0, 1, 2].map(|column| {
        offset[0] * rotation[0][column] + offset[1] * rotation[1][column] + offset[2] * rotation[2][column]
    });
    (offset, extract_angles(matrix))
}

fn build_rotation([pitch, yaw, roll]: [f32; 3]) -> [[f32; 3]; 3] {
    let (sx, cx) = sin_cos(pitch);
    let (sy, cy) = sin_cos(yaw);
    let (sz, cz) = sin_cos(roll);
    [
        [-(sz * sy) * sx + cz * cy, sz * cy * sx + cz * sy, -sz * cx],
        [-sy * cx, cy * cx, sx],
        [cz * sy * sx + sz * cy, -sx * cz * cy + sz * sy, cz * cx],
    ]
}

fn sin_cos(angle: f32) -> (f32, f32) {
    let mut normalized = angle.rem_euclid(360.0);
    if normalized == 360.0 {
        normalized = 0.0;
    }
    let scaled = normalized * 45.511112_f32;
    let index = scaled.floor() as usize;
    let fraction = scaled - index as f32;
    let sample = |i: usize| {
        let i = i & 0x3fff;
        let (index, negative) = match i {
            0..=0x0fff => (i, false),
            0x1000..=0x1fff => (0x1fff - i, false),
            0x2000..=0x2fff => (i - 0x2000, true),
            _ => (0x3fff - i, true),
        };
        let value = f32::from_bits(SINE_TABLE[index]);
        if negative { -value } else { value }
    };
    let interpolate = |i| {
        let first = sample(i);
        (sample(i + 1) - first) * fraction + first
    };
    (interpolate(index), interpolate(index + 0x1000))
}

fn multiply(a: [[f32; 3]; 3], b: [[f32; 3]; 3]) -> [[f32; 3]; 3] {
    let mut result = [[0.0; 3]; 3];
    for row in 0..3 {
        for col in 0..3 {
            result[row][col] = a[row][0] * b[0][col] + a[row][1] * b[1][col] + a[row][2] * b[2][col];
        }
    }
    result
}

fn extract_angles(m: [[f32; 3]; 3]) -> [f32; 3] {
    let x = m[1][0];
    let y = m[1][1];
    let z = m[1][2];
    let length_squared = y * y + x * x;
    let length = length_squared.sqrt();
    let mut angles = [0.0; 3];
    if length >= 0.001 {
        angles[1] = 90.0 - arc_sin3(y / length);
        if x > 0.0 { angles[1] = -angles[1]; }
        let cos_pitch = length_squared / length;
        if cos_pitch < 1.0 {
            angles[0] = 90.0 - arc_sin3(cos_pitch);
        }
        let cos_roll = (-m[0][1] * x + y * m[0][0]) / length;
        angles[2] = if cos_roll >= 1.0 { 0.0 } else if cos_roll <= -1.0 { 180.0 } else { 90.0 - arc_sin3(cos_roll) };
        if m[0][2] > 0.0 { angles[2] = -angles[2]; }
    } else {
        angles[0] = 90.0;
        angles[2] = 90.0 - arc_sin3(m[0][0]);
        if (-m[0][1] > 0.0 && z > 0.0) || (-m[0][1] < 0.0 && z < 0.0) {
            angles[2] = -angles[2];
        }
    }
    if z < 0.0 { angles[0] = -angles[0]; }
    angles
}

fn arc_sin3(value: f32) -> f32 {
    let magnitude = value.abs();
    let x = if magnitude <= 0.70710677 {
        magnitude
    } else {
        (1.0 - magnitude * magnitude).sqrt()
    };
    let power = |n: usize| {
        let mut result = x;
        for _ in 1..n {
            result *= x;
        }
        result
    };
    let first = (power(3) as f64 / 6.0 + x as f64) as f32;
    let second = (power(5) as f64 * 0.075_f32 as f64 + first as f64) as f32;
    let degrees = ((power(7) as f64 * 0.066797_f32 as f64 + second as f64)
        * 57.295784_f32 as f64) as f32;
    let result = if magnitude <= 0.70710677 { degrees } else { 90.0 - degrees };
    if value < 0.0 { -result } else { result }
}

