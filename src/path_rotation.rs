mod tests {
    #[test]
    fn engine_deadband_is_strictly_below_two_and_a_half_degrees() {
        assert!(!PathRotation::prepare([0.0; 3], [0.0, 2.49, 0.0], 1.0).active);
        assert!(PathRotation::prepare([0.0; 3], [0.0, 2.5, 0.0], 1.0).active);
    }

    use super::*;
    #[test]
    fn sine_table_quadrants_match_engine_axes() {
        assert_eq!(sin_cos(0.0), (0.0, 1.0));
        assert_eq!(sin_cos(90.0), (1.0, 0.0));
        assert_eq!(sin_cos(180.0), (0.0, -1.0));
        assert_eq!(sin_cos(270.0), (-1.0, 0.0));
    }


    #[test]
    fn orientation_composes_and_snaps_to_target() {
        let mut rotation = PathRotation::prepare([20.0, 30.0, 10.0], [50.0, 70.0, -20.0], 2.0);
        rotation.advance(1.0);
        assert!(rotation.active);
        assert_eq!(rotation.progress, 0.5);
        assert_ne!(rotation.matrix, build_rotation([35.0, 50.0, -5.0]));
        rotation.advance(1.0);
        assert!(!rotation.active);
        assert_eq!(rotation.matrix, build_rotation(rotation.target));
    }
}
